export function detectLang(): Lang {
  const saved = (() => {
    try {
      return localStorage.getItem('lang')
    } catch {
      return null
    }
  })()
  if (saved === 'kz' || saved === 'ru' || saved === 'en') return saved
  const q = new URLSearchParams(location.search).get('lang')
  if (q === 'kz' || q === 'ru' || q === 'en') return q
  const nav = (navigator.languages || [navigator.language]).map(l => l.toLowerCase())
  if (nav.some(l => l.startsWith('kk'))) return 'kz'
  if (nav.some(l => l.startsWith('ru') || l.startsWith('uk') || l.startsWith('be') || l.startsWith('ky') || l.startsWith('uz'))) return 'ru'
  return 'en'
}

export function fmt(s: string, vars: Record<string, string | number> = {}): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`))
}
